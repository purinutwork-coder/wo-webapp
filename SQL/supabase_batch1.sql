-- ---------------------------------------------------------------------
--  1) ขอบเขตวันการทำงาน (SPEC 9.2 · 13)
--
--  Admin กรอกเฉพาะบางใบที่รู้ว่ามีเงื่อนไข เช่นรอของแล้วไม่รู้วันแน่นอน
--  ใบส่วนใหญ่จึงเว้นว่าง — คอลัมน์นี้จึงต้องยอมให้เป็น NULL ได้
--  และ NULL ต้องแปลว่า "ไม่มีกำหนด" ไม่ใช่ "เกินกำหนด"
-- ---------------------------------------------------------------------
alter table work_order
  add column if not exists duration_days integer;

comment on column work_order.duration_days is
  'จำนวนวันตามปฏิทินที่ให้ทำงานให้เสร็จ นับจากวันที่เปิดใบงานตามเวลาไทย · NULL = ไม่ได้กำหนดขอบเขต';


-- ---------------------------------------------------------------------
--  2) วันครบกำหนด — computed field ของ PostgREST ไม่ใช่คอลัมน์ที่เก็บค่า
--
--  **ห้ามเก็บวันครบกำหนดเป็นคอลัมน์แยกเด็ดขาด** ถ้าเก็บทั้งวันที่เปิดใบ
--  จำนวนวัน และวันครบกำหนด วันหนึ่งสามค่านี้จะไม่ตรงกัน แล้วไม่มีใครรู้ว่าอันไหนถูก
--
--  ฟังก์ชันที่รับทั้งแถวเป็นอาร์กิวเมนต์แบบนี้ PostgREST จะเปิดให้ใช้เหมือน
--  คอลัมน์หนึ่งของตารางนั้น — กรองได้ เรียงได้ เลือกมาแสดงได้ — โดยไม่เก็บอะไรเลย
--  จึงไม่มีสำเนาให้เพี้ยน และสูตรคำนวณมีอยู่ที่เดียวในฐานข้อมูลทั้งก้อน
--
--  ** ทำไมเป็น INTERVAL '+07:00' ไม่ใช่ 'Asia/Bangkok' **
--
--  `timestamptz AT TIME ZONE 'ชื่อโซน'` ถูกประกาศว่า STABLE เพราะฐานข้อมูล
--  ต้องเปิดตารางโซนเวลาอ่าน ซึ่งแก้ไขได้ระหว่างทาง · ฟังก์ชัน STABLE สร้าง index
--  ไม่ได้ · ส่วน `AT TIME ZONE INTERVAL` เป็น IMMUTABLE เพราะไม่ต้องเปิดตารางอะไร
--
--  สองแบบให้ผลเท่ากันทุกค่าสำหรับประเทศไทย เพราะไทยใช้ +07:00 มาตั้งแต่ พ.ศ. 2463
--  และไม่เคยมีเวลาออมแสง · ใบสั่งงานใบแรกของระบบนี้เปิดปี 2026 จึงไม่มีทางแตะช่วงก่อนนั้น
--  ถ้าวันหนึ่งประเทศไทยเปลี่ยนเขตเวลา ต้องกลับมาแก้บรรทัดนี้พร้อมกับ TIMEZONE
--  ใน 00_Config.gs — ทั้งสองที่ผูกกับข้อเท็จจริงเดียวกัน
-- ---------------------------------------------------------------------
create or replace function public.due_date(work_order)
returns date
language sql
immutable
as $$
  select (($1.created_date at time zone interval '+07:00')::date + $1.duration_days)
$$;

comment on function public.due_date(work_order) is
  'วันครบกำหนดของใบงาน = วันที่เปิดใบตามเวลาไทย บวก duration_days · คำนวณทุกครั้ง ไม่ได้เก็บไว้ · NULL เมื่อไม่ได้กำหนดขอบเขตวัน';

-- เปิดให้เรียกได้เหมือนคอลัมน์ · service_role เท่านั้น เหมือนทุกอย่างในระบบนี้
revoke all on function public.due_date(work_order) from public, anon, authenticated;
grant execute on function public.due_date(work_order) to service_role;

/*
  index ของตัวกรอง "เลยกำหนด"

  ตัวกรองยิงมาพร้อมกันสองเงื่อนไขเสมอ คือ duration_days is not null กับ
  due_date < วันนี้ · เงื่อนไขแรกมีไว้ให้ตัวเลือกแผนงานหยิบ index บางส่วนตัวนี้ได้
  ถ้าส่งมาแต่เงื่อนไขที่สอง Postgres ต้องไล่อ่านทั้งตารางเพื่อพิสูจน์ว่าแถวไหนเข้าข่าย

  เป็น index บางส่วน เพราะใบงานส่วนใหญ่ไม่ได้กำหนดขอบเขตวัน · index จึงเล็กกว่า
  จำนวนใบงานทั้งหมดมาก และโตตามจำนวนใบที่มีเงื่อนไขจริงเท่านั้น
*/
create index if not exists idx_wo_due
  on work_order ((((created_date at time zone interval '+07:00')::date + duration_days)))
  where duration_days is not null;


-- ---------------------------------------------------------------------
--  3) กำหนดวันเวลาเข้างานของแผนก (SPEC 13 · 17.3)
--
--  **เป็น text ไม่ใช่ timestamptz** เพราะเป็นเวลานัดหมายที่คนกรอก
--  เก็บสตริง 'YYYY-MM-DDTHH:mm' ตามที่ผู้ใช้เห็นบนจอ เหมือน start_date / end_date
--  ของใบงาน (กฎข้อ 23) · รูปแบบนี้เรียงลำดับแบบข้อความได้ถูกต้องอยู่แล้ว
--  และกรองด้วยคำนำหน้าวันที่ได้ตรง ๆ ซึ่งเป็นวิธีที่หน้า "งานวันนี้" ใช้
--
--  เก็บแยกจาก work_order.start_date / end_date โดยตั้งใจ — สองอย่างนี้ตอบคนละคำถาม
--  ของใบงานคือสิ่งที่ตกลงกับลูกค้า ของแผนกคือวันที่ช่างไปจริง
--  ถ้าใช้ช่องเดียวกันแล้วแผนกเขียนทับ คำถาม "เลยกำหนดแล้วช่างนัดไว้วันไหน"
--  จะตอบไม่ได้เลย ซึ่งเป็นคำถามหลักของข้อ 1 ข้างบน
-- ---------------------------------------------------------------------
alter table department_task
  add column if not exists visit_start text;
alter table department_task
  add column if not exists visit_end   text;

comment on column department_task.visit_start is
  'เวลานัดหมายที่ช่างเข้างานจริง สตริง YYYY-MM-DDTHH:mm ตามเวลาไทย · ห้ามเป็น timestamptz (กฎข้อ 23)';
comment on column department_task.visit_end is
  'เวลานัดหมายที่ช่างออกจากงาน สตริง YYYY-MM-DDTHH:mm ตามเวลาไทย · ห้ามเป็น timestamptz (กฎข้อ 23)';

/*
  index ของหน้า "งานวันนี้"

  คำถามคือ "งานของแผนกนี้ ที่นัดไว้วันนี้ และยังไม่เสร็จ" · สามเงื่อนไขมาพร้อมกันเสมอ
  เรียงคอลัมน์ให้ตรงกับลำดับที่ถูกใช้: แผนกก่อน (เท่ากับพอดี) แล้วค่อยวันเวลา (คำนำหน้า)

  text_pattern_ops จำเป็นสำหรับการค้นด้วยคำนำหน้า (like 'YYYY-MM-DD%')
  ถ้าใช้ตัวเปรียบเทียบปกติ Postgres จะใช้ index ตัวนี้ก็ต่อเมื่อ collation ของฐานข้อมูล
  เป็น C เท่านั้น ซึ่งของ Supabase ไม่ใช่ — index จะถูกสร้างแล้วไม่เคยถูกใช้เลย
  โดยไม่มีอะไรฟ้อง นอกจากคำสั่งช้าลงเรื่อย ๆ ตามจำนวนงาน
*/
create index if not exists idx_dt_visit
  on department_task (department, visit_start text_pattern_ops)
  where visit_start is not null;


-- ---------------------------------------------------------------------
--  ตรวจว่าใช้ได้จริง
-- ---------------------------------------------------------------------

-- ควรได้สามแถว: duration_days / visit_start / visit_end
select table_name, column_name, data_type
from information_schema.columns
where (table_name = 'work_order'      and column_name = 'duration_days')
   or (table_name = 'department_task' and column_name in ('visit_start', 'visit_end'))
order by table_name, column_name;

-- ควรได้วันครบกำหนดของทุกใบที่กรอกขอบเขตวันไว้ · ใบที่ไม่ได้กรอกต้องได้ NULL
select w.wo_id, w.created_date, w.duration_days, due_date(w) as due
from work_order w
order by w.created_date desc
limit 10;


-- ---------------------------------------------------------------------
--  พิสูจน์สูตรวันครบกำหนดโดยไม่ต้องมีใบงานจริง
-- ---------------------------------------------------------------------
/*
  ตราบใดที่ยังไม่มีใบงานที่กรอกขอบเขตวันไว้ checkSupabase() ข้อ 9 จะบอกได้แค่ว่า
  "เรียกสูตรได้" แต่เทียบสองฝั่งไม่ได้ · ช่วงเวลานั้นคือช่วงที่เสี่ยงที่สุด เพราะสูตรที่
  ผิดเรื่องโซนเวลาจะดูเหมือนถูกทุกประการจนกว่าจะมีใบงานที่เปิดในชั่วโมงที่ต่างกัน

  บล็อกนี้ป้อนเวลาสมมติเข้าไปในฟังก์ชันตัวจริง (ไม่ใช่เขียนสูตรซ้ำ ซึ่งจะพิสูจน์
  ได้แค่ว่าสำเนาสองชุดเหมือนกัน) โดยใช้ jsonb_populate_record ประกอบแถว work_order
  ขึ้นมาเฉพาะสองคอลัมน์ที่สูตรใช้ · ไม่เขียนอะไรลงตาราง อ่านอย่างเดียว รันซ้ำได้เสมอ

  **ทุกแถวต้องได้ตรงกับช่อง "ควรได้" ถ้ามีแถวใดไม่ตรง แปลว่าสูตรคิดบนวัน UTC
  ไม่ใช่วันไทย และใบงานทุกใบที่เปิดก่อนเจ็ดโมงเช้าจะมีวันครบกำหนดเลื่อนไปหนึ่งวัน**
*/
with cases(ที่, created, days, ควรได้, เหตุผล) as (
  values
    (1, timestamptz '2026-09-30 23:30:00+00',  5, date '2026-10-06',
        'เก็บเป็น 23:30 UTC ของวันสุดท้ายของเดือน = 06:30 ของวันที่ 1 ตุลาคมตามเวลาไทย จึงต้องนับจากวันที่ 1'),
    (2, timestamptz '2026-09-30 23:30:00+07',  5, date '2026-10-05',
        'เปิดใบสี่ทุ่มครึ่งตามเวลาไทยของวันสุดท้ายของเดือน ยังเป็นวันที่ 30 อยู่'),
    (3, timestamptz '2026-10-01 00:30:00+07',  1, date '2026-10-02',
        'เที่ยงคืนครึ่งตามเวลาไทย = 17:30 ของวันก่อนหน้าตาม UTC ซึ่งเป็นคนละเดือน'),
    (4, timestamptz '2026-01-31 10:00:00+07', 30, date '2026-03-02',
        'บวกข้ามเดือนที่มี 28 วัน ต้องให้ Postgres เป็นคนคิด ไม่ใช่คูณ 86400000 เอง'),
    (5, timestamptz '2026-12-31 20:00:00+00',  1, date '2027-01-02',
        'สามทุ่มของวันสิ้นปีตาม UTC คือปีใหม่แล้วตามเวลาไทย จึงต้องข้ามปีไปด้วย'),
    (6, timestamptz '2026-05-05 09:00:00+07', null, null,
        'ไม่ได้กรอกขอบเขตวัน ต้องได้ NULL ไม่ใช่วันนี้ และไม่ใช่ศูนย์วัน')
)
select
  ที่,
  created,
  days                                            as "จำนวนวัน",
  (created at time zone 'Asia/Bangkok')::date     as "วันไทยที่เปิดใบ",
  (created at time zone 'UTC')::date              as "วัน UTC (ห้ามใช้)",
  due_date(jsonb_populate_record(null::work_order,
    jsonb_build_object('created_date', created, 'duration_days', days))) as "สูตรให้",
  ควรได้,
  case
    when due_date(jsonb_populate_record(null::work_order,
      jsonb_build_object('created_date', created, 'duration_days', days)))
      is not distinct from ควรได้ then 'ผ่าน'
    else '!! ไม่ตรง'
  end                                             as "ผล",
  เหตุผล
from cases
order by ที่;

/*
  index ใช้ INTERVAL '+07:00' ส่วนฟังก์ชันอ่านง่ายกว่าถ้าเขียนชื่อโซน · สองแบบนี้
  ต้องให้ค่าเท่ากันเสมอสำหรับประเทศไทย (คงที่ +07:00 มาตั้งแต่ปี 1920 ไม่มี DST)
  ถ้าวันใดไม่เท่ากัน Postgres จะเลิกใช้ index เงียบ ๆ แล้วตัวกรอง "เลยกำหนด"
  จะช้าลงเรื่อย ๆ ตามจำนวนใบงานโดยไม่มีอะไรฟ้อง

  ควรได้ศูนย์แถว
*/
select t as "ชั่วโมงที่สองแบบให้ค่าไม่ตรงกัน"
from generate_series(timestamptz '2026-01-01', timestamptz '2027-01-01', interval '1 hour') t
where (t at time zone 'Asia/Bangkok')::date <> (t at time zone interval '+07:00')::date;


-- ---------------------------------------------------------------------
--  เวอร์ชันของไฟล์นี้ — checkSupabase() อ่านค่านี้ไปเทียบกับที่โค้ดคาดหวัง
--  (ขอบเขตวันการทำงาน และวันเวลาเข้างานของแผนก)
--  ห้ามใช้คอมเมนต์บอกเวอร์ชันแทน เพราะอ่านกลับจากฐานข้อมูลไม่ได้
-- ---------------------------------------------------------------------
create or replace function sql_version_batch1() returns text
  language sql immutable as $$ select 'batch1-2026-09-26-a' $$;
revoke all on function sql_version_batch1() from public, anon, authenticated;
grant execute on function sql_version_batch1() to service_role;

